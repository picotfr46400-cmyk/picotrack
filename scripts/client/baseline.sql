CREATE OR REPLACE FUNCTION public.finish_mail_outbox(p_id uuid, p_environment_code text, p_attempts integer, p_attempt_id uuid, p_status text, p_last_error text, p_warning text, p_subject text, p_recipients jsonb)
 RETURNS SETOF mail_outbox
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_row public.mail_outbox%rowtype;
begin
  if p_attempt_id is null or p_status not in ('sent', 'failed') then
    return;
  end if;

  update public.mail_outbox
  set status = p_status,
      last_error = p_last_error,
      warning = p_warning,
      subject = p_subject,
      recipients = coalesce(p_recipients, recipients),
      claimed_until = null,
      updated_at = now()
