CREATE OR REPLACE FUNCTION public.picotrack_appointment_capacity(p_environment_code text, p_form_id text, p_field_id text)
 RETURNS integer
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
