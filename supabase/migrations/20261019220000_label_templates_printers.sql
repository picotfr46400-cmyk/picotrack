-- Étiquettes et imprimantes PicoTrack.
-- À appliquer à la main, une base client à la fois. L'application ne lance pas ce fichier.
-- Accès uniquement par l'API (service_role) : RLS active, aucune policy, aucun droit anon/authenticated.

create table if not exists public.printer_profiles (
  id bigint generated by default as identity primary key,
  environment_code text not null,
  name text not null,
  kind text not null default 'system',
  width_mm numeric(6,1) not null default 100,
  height_mm numeric(6,1) not null default 50,
  margin_mm numeric(4,1) not null default 0,
  dpi integer not null default 203,
  notes text not null default '',
  is_default boolean not null default false,
  created_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint printer_profiles_kind_check check (kind in ('system', 'zpl')),
  constraint printer_profiles_size_check check (width_mm between 10 and 300 and height_mm between 10 and 300),
  constraint printer_profiles_margin_check check (margin_mm between 0 and 20),
  constraint printer_profiles_dpi_check check (dpi in (150, 203, 300, 600))
);

create index if not exists printer_profiles_env_idx on public.printer_profiles (environment_code);

create table if not exists public.label_templates (
  id bigint generated by default as identity primary key,
  environment_code text not null,
  name text not null,
  form_id bigint,
  width_mm numeric(6,1) not null default 100,
  height_mm numeric(6,1) not null default 50,
  elements jsonb not null default '[]'::jsonb,
  printer_profile_id bigint references public.printer_profiles (id) on delete set null,
  created_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint label_templates_size_check check (width_mm between 10 and 300 and height_mm between 10 and 300),
  constraint label_templates_elements_check check (jsonb_typeof(elements) = 'array')
);

create index if not exists label_templates_env_form_idx on public.label_templates (environment_code, form_id);

alter table public.printer_profiles enable row level security;
alter table public.label_templates enable row level security;
revoke all on public.printer_profiles from anon, authenticated;
revoke all on public.label_templates from anon, authenticated;
